-- El login acepta "OSCAR COTA" además del correo: esta función traduce el usuario a su correo.
create or replace function public.correo_de_usuario(p_usuario text)
returns text language sql stable security definer set search_path = '' as $$
  select p.email from public.perfiles p
  where p.usuario is not null and upper(p.usuario) = upper(trim(p_usuario)) and p.activo
  limit 1
$$;
grant execute on function public.correo_de_usuario(text) to anon, authenticated;

